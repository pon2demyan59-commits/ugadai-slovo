-- Word game data is separate from the chess tables. Private tables have no client grants.
create schema if not exists word_game_private;
revoke all on schema word_game_private from public;
grant usage on schema word_game_private to anon, authenticated;
create table word_game_private.questions (
  word text primary key, category text not null, level smallint not null check(level between 1 and 5)
);
create table word_game_private.players (
  user_id uuid primary key references auth.users(id) on delete cascade,
  nickname text not null check(char_length(nickname) between 2 and 24),
  solved_count integer not null default 0 check(solved_count between 0 and 1000),
  seals integer not null default 0 check(seals between 0 and 10),
  reached_at timestamptz not null default now()
);
create index word_game_ranking on word_game_private.players(solved_count desc,reached_at,user_id);
create table word_game_private.solutions (
  user_id uuid not null references word_game_private.players(user_id) on delete cascade,
  word text not null references word_game_private.questions(word),
  primary key(user_id,word)
);
create index word_game_solutions_word on word_game_private.solutions(word);
create table word_game_private.completions (
  user_id uuid primary key references word_game_private.players(user_id) on delete cascade,
  completion_no bigint not null unique check(completion_no>0),
  completed_at timestamptz not null default now()
);
create table word_game_private.completion_counter (
  singleton boolean primary key default true check(singleton), last_no bigint not null default 0
);
insert into word_game_private.completion_counter(singleton,last_no) values(true,0);
alter table word_game_private.questions enable row level security;
alter table word_game_private.players enable row level security;
alter table word_game_private.solutions enable row level security;
alter table word_game_private.completions enable row level security;
alter table word_game_private.completion_counter enable row level security;
create policy word_player_own on word_game_private.players for select to authenticated using(user_id=(select auth.uid()));
create policy word_solutions_own on word_game_private.solutions for select to authenticated using(user_id=(select auth.uid()));
create policy word_completion_own on word_game_private.completions for select to authenticated using(user_id=(select auth.uid()));
revoke all on all tables in schema word_game_private from anon, authenticated;

-- Only the caller's authenticated identity can be changed; counts and completion order are server derived.
create function word_game_private.sync_progress(p_nickname text,p_words text[])
returns jsonb language plpgsql security definer set search_path='' as $$
declare
  caller uuid := auth.uid(); total integer; old_total integer; seal_count integer; issued bigint;
  nick text := regexp_replace(trim(coalesce(p_nickname,'')),'\s+',' ','g');
begin
  if caller is null then raise exception 'Sign in required' using errcode='42501'; end if;
  if coalesce(cardinality(p_words),0)>1000 then raise exception 'Too many words'; end if;
  if char_length(nick)<2 or char_length(nick)>24 or nick !~* '^[a-zа-яё0-9 _-]+$' then nick:='Игрок'; end if;
  if exists(select 1 from unnest(coalesce(p_words,'{}'::text[])) w
    where w is null or not exists(select 1 from word_game_private.questions q where q.word=w)) then
    raise exception 'Unknown word';
  end if;
  insert into word_game_private.players(user_id,nickname) values(caller,nick)
    on conflict(user_id) do update set nickname=excluded.nickname;
  select solved_count into old_total from word_game_private.players where user_id=caller for update;
  insert into word_game_private.solutions(user_id,word)
    select caller,w from (select distinct unnest(coalesce(p_words,'{}'::text[])) as w) t
    on conflict do nothing;
  select count(*) into total from word_game_private.solutions where user_id=caller;
  select count(*) into seal_count from (
    select q.category from word_game_private.solutions s join word_game_private.questions q using(word)
    where s.user_id=caller group by q.category having count(*)=100
  ) complete;
  update word_game_private.players set solved_count=total,seals=seal_count,
    reached_at=case when total>old_total then clock_timestamp() else reached_at end where user_id=caller;
  if total=1000 and not exists(select 1 from word_game_private.completions where user_id=caller) then
    update word_game_private.completion_counter set last_no=last_no+1 where singleton returning last_no into issued;
    insert into word_game_private.completions(user_id,completion_no,completed_at) values(caller,issued,clock_timestamp());
  end if;
  return jsonb_build_object('solved',total,'seals',seal_count,'completion_no',
    (select completion_no from word_game_private.completions where user_id=caller));
end $$;
revoke all on function word_game_private.sync_progress(text,text[]) from public,anon,authenticated;
grant execute on function word_game_private.sync_progress(text,text[]) to authenticated;
create function public.word_game_sync(p_nickname text,p_words text[])
returns jsonb language sql security invoker set search_path='' as $$
  select word_game_private.sync_progress(p_nickname,p_words);
$$;
revoke all on function public.word_game_sync(text,text[]) from public,anon,authenticated;
grant execute on function public.word_game_sync(text,text[]) to authenticated;

-- Deliberately public read API: nicknames and game achievements only, no account UUIDs or tokens.
create function word_game_private.standings()
returns jsonb language sql stable security definer set search_path='' as $$
with ranked as (
  select p.*,row_number() over(order by p.solved_count desc,p.reached_at,p.user_id) as rank,
    c.completion_no,c.completed_at
  from word_game_private.players p left join word_game_private.completions c using(user_id)
  where p.solved_count>0
), formatted as (
  select *,jsonb_build_object('nickname',nickname,'solved',solved_count,'seals',seals,'rank',rank,
    'completion_no',completion_no,'completed_at',completed_at,'is_me',coalesce(user_id=auth.uid(),false)) as entry from ranked
)
select jsonb_build_object(
  'target',1000,'players',(select count(*) from ranked),
  'finishers',(select count(*) from word_game_private.completions),
  'top',coalesce((select jsonb_agg(entry order by rank) from formatted where rank<=10),'[]'::jsonb),
  'pioneers',coalesce((select jsonb_agg(entry order by completion_no) from (
    select entry,completion_no from formatted where completion_no is not null order by completion_no limit 10
  ) f),'[]'::jsonb),
  'self',(select entry from formatted where user_id=auth.uid()),
  'cutoff',(select solved_count from ranked where rank=10)
);
$$;
revoke all on function word_game_private.standings() from public,anon,authenticated;
grant execute on function word_game_private.standings() to anon,authenticated;
create function public.word_game_standings()
returns jsonb language sql stable security invoker set search_path='' as $$ select word_game_private.standings(); $$;
revoke all on function public.word_game_standings() from public,anon,authenticated;
grant execute on function public.word_game_standings() to anon,authenticated;

