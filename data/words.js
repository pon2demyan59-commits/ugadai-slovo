const ENDINGS = ["н", "р", "т", "к", "м", "с", "л", "в", "д", "з"];

function makeHint(word, index) {
  const number = String(index + 1).padStart(4, "0");
  return "Слово " + number + ": состоит из " + word.length + " букв. Первая буква: " + word[0].toUpperCase() + ".";
}

function createWordBank() {
  const words = [];
  const used = new Set();

  for (const word of REAL_WORDS) {
    if (/^[а-яё]{5}$/.test(word) && !used.has(word)) {
      words.push(word);
      used.add(word);
    }
  }

  for (const first of SYLLABLES) {
    for (const second of SYLLABLES) {
      for (const ending of ENDINGS) {
        const word = first + second + ending;

        if (/^[а-яё]{5}$/.test(word) && !used.has(word)) {
          words.push(word);
          used.add(word);
        }

        if (words.length >= 1000) {
          return words.slice(0, 1000);
        }
      }
    }
  }

  return words.slice(0, 1000);
}

const GAME_WORDS = createWordBank().map((word, index) => ({
  word,
  hint: makeHint(word, index)
}));
